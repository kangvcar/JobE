function slug(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9\u4e00-\u9fff]+/g, "_")
    .replace(/^_|_$/g, "");
}

function skillId(name: string): string {
  return `skill_${slug(name)}`;
}

export const LEVEL_PARENTS = {
  foundation: { id: "level_foundation", name: "基础层" },
  method: { id: "level_method", name: "方法层" },
  application: { id: "level_application", name: "应用层" },
} as const;

export type BuiltCatalog = {
  skills: Skill[];
  clusters: SkillCluster[];
  skillLevel: Record<string, keyof typeof LEVEL_PARENTS>;
};

export function buildSkills(): BuiltCatalog {
  const skills: Skill[] = [];
  const clusters: SkillCluster[] = [];
  const skillLevel: Record<string, keyof typeof LEVEL_PARENTS> = {};
  const seen = new Set<string>();

  for (const cluster of CLUSTER_SEEDS) {
    const extra = EXTRA_SKILLS.find((e) => e.cluster === cluster.id)?.items ?? [];
    const all = [...cluster.skills, ...extra];
    const ids: string[] = [];
    let foundationParent: string | null = null;
    for (const seed of all) {
      const id = skillId(seed.name);
      if (seen.has(id)) continue;
      seen.add(id);
      const parent_id =
        seed.level === "foundation"
          ? null
          : seed.level === "method"
            ? foundationParent
            : ids[0] ?? null;
      if (seed.level === "foundation" && !foundationParent) foundationParent = id;
      skills.push({
        id,
        name: seed.name,
        aliases: seed.aliases ?? [],
        parent_id,
        cluster_id: cluster.id,
        ontology_version: ONTOLOGY_VERSION,
        external_ids: {},
      });
      skillLevel[id] = seed.level;
      ids.push(id);
    }
    clusters.push({
      id: cluster.id,
      name: cluster.name,
      skill_ids: ids,
      ontology_version: ONTOLOGY_VERSION,
    });
  }

  return { skills, clusters, skillLevel };
}

