export function buildRoles(skillByName: Map<string, Skill>): {
  roles: Role[];
  families: RoleFamily[];
  roleSkillIds: Record<string, string[]>;
} {
  const roleSkillIds: Record<string, string[]> = {};
  const roles: Role[] = ROLE_SEEDS.map((seed) => {
    const ids = seed.skill_names
      .map((n) => skillByName.get(n)?.id)
      .filter((id): id is string => Boolean(id));
    roleSkillIds[seed.id] = ids;
    return {
      id: seed.id,
      name: seed.name,
      family_id: seed.family_id,
      responsibilities: seed.responsibilities,
      scenarios: seed.scenarios,
      occupation_code: seed.occupation_code,
      is_emerging: seed.is_emerging,
      state: seed.state,
      signal_strength: seed.signal_strength,
      evidence_ids: [],
      created_at: "2024-03-12T09:00:00+08:00",
      updated_at: "2026-01-18T11:20:00+08:00",
    };
  });

  const families = FAMILY_SEEDS.map((f) => ({
    ...f,
    role_ids: roles.filter((r) => r.family_id === f.id).map((r) => r.id),
  }));

  return { roles, families, roleSkillIds };
}

